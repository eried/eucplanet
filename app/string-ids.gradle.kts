// The R.string id of every string shared code names, for AndroidStrings.
//
// Shared code says Res.string.<key>; on Android that must still show the
// phone app's own R.string.<key>, read and formatted by Resources as before.
// This scans :shared's commonMain for the keys it names and writes the
// key-to-id table the app installs at start (EucPlanetApp). Only those keys,
// so the resource shrinker keeps exactly what it kept before.
//
// Writes StringIds.kt into build/generated; nothing is committed.

abstract class StringIdsTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sources: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val key = Regex("""\bRes\.string\.(\w+)""")
        val keys = sources.files.filter { it.extension == "kt" }
            .flatMap { f -> key.findAll(f.readText()).map { it.groupValues[1] } }
            .toSortedSet()
        val sb = StringBuilder()
        sb.append("package com.eried.eucplanet\n\n")
        sb.append("// Generated by app/string-ids.gradle.kts from the keys :shared names.\n\n")
        sb.append("internal object StringIds {\n")
        sb.append("    private val ids: Map<String, Int> by lazy {\n")
        sb.append("        HashMap<String, Int>(${keys.size * 2 + 16}).also { m ->\n")
        val chunks = keys.chunked(400)
        chunks.indices.forEach { sb.append("            fill$it(m)\n") }
        sb.append("        }\n    }\n\n")
        sb.append("    fun id(key: String): Int = ids[key] ?: 0\n")
        chunks.forEachIndexed { i, chunk ->
            sb.append("\n    private fun fill$i(m: HashMap<String, Int>) {\n")
            chunk.forEach { sb.append("        m[\"").append(it).append("\"] = R.string.").append(it).append('\n') }
            sb.append("    }\n")
        }
        sb.append("}\n")
        val out = outputDir.get().asFile.resolve("com/eried/eucplanet")
        out.mkdirs()
        out.resolve("StringIds.kt").writeText(sb.toString())
    }
}

tasks.register<StringIdsTask>("generateStringIds") {
    sources.from(fileTree(rootProject.file("shared/src/commonMain/kotlin")))
    outputDir.set(layout.buildDirectory.dir("generated/stringIds"))
}
